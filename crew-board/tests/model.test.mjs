import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../mods/crew-board/model.js', import.meta.url), 'utf8');
const { collectCrew, crewRole, remember, missingCrew, confirmExits, groupJobs, elapsed } = await import(`data:text/javascript,${encodeURIComponent(source)}`);
const spaces = [{id:'s1', name:'api', tabs:[{id:'tab1', name:'auth', index:1, settled:true}]}];
const agent = { address:'t1', pane:'p1', space:'s1', space_name:'api', tab:'tab1', tab_name:'auth', status:'done', title:'refresh cache', seq:1 };
const raw = [{address:'t1',state:'live',status_ms:1000}, {address:'t2',parent:'t1',state:'live',status:'error',report:{kind:'auth',msg:'Sign in'}}, {address:'t3',parent:'t2',state:'live',status:'done'}, {address:'t4',state:'live',program:{shell:true}}];
const live = collectCrew([agent],raw,spaces);
assert.equal(live.length,3);
assert.equal(live.find(x=>x.address==='t1').status,'done');
assert.equal(live.find(x=>x.address==='t2').status,'blocked');
assert.equal(live.find(x=>x.address==='t2').space_name,'api');
assert.equal(live.find(x=>x.address==='t3').status,'idle');
assert.equal(live.find(x=>x.address==='t3').rawDone,true);
assert.equal(crewRole(agent.address),crewRole({...agent,seq:999}.address));
assert.equal(collectCrew([{...agent,status:'idle'}],raw,spaces)[0].status,'idle');
const remote = collectCrew([], [{address:'edge/t9',parent:'edge/t8',state:'live',status:'blocked',labels:{'herdr.space':'s2','herdr.tab':'tab2'}}], [{id:'edge/s2',name:'ops',machine:'edge',tabs:[{id:'edge/tab2',name:'ci'}]}]);
assert.equal(remote[0].space_name,'ops');
const history = remember([],live,5000);
assert.equal(missingCrew(history,[],[]).every(a=>a.status==='unavailable'),true);
assert.equal(missingCrew(history,[],raw).length,0);
assert.equal(missingCrew(confirmExits(history,{terminals:[]},new Set()),[],[])[0].status,'unavailable');
const confirmed = confirmExits(history,{terminals:[{address:'t1',state:'finished',exit_code:0,reason:'exited'}]},new Set());
assert.equal(missingCrew(confirmed,[],[]).find(a=>a.address==='t1').status,'dead');
assert.equal(missingCrew(remember(confirmed,live,6000),[],[]).find(a=>a.address==='t1').status,'unavailable');
assert.throws(()=>confirmExits(history,{terminals:'broken'},new Set()));
assert.equal(remember([],Array.from({length:200},(_,i)=>({...agent,address:`t${i}`})),1000).length,128);
assert.equal(groupJobs([],missingCrew(confirmed,[],[]))[0].tabs[0].crew.length,3);
assert.equal(elapsed(1000,61000),'1m');
assert.equal(elapsed(null,61000),'');
assert.equal(collectCrew([], [{address:'cycle1',parent:'cycle2',status:'blocked'},{address:'cycle2',parent:'cycle1',status:'working'}],[]).length,2);
const named={...agent,program:{name:'Agent program'}};
const titleRows=[{address:'unrelated',report:{title:'Wrong task'}},{address:'t1',state:'live',report:{title:'Reported task'},status_ms:777}];
assert.equal(collectCrew([named],titleRows,spaces)[0].title,'refresh cache');
const reportOnly=collectCrew([{...named,title:''}],titleRows,spaces)[0];
assert.equal(reportOnly.title,'Reported task');assert.equal(reportOnly.status_ms,777);
assert.equal(collectCrew([{...named,title:''}],[],spaces)[0].title,'Agent program');
assert.equal(collectCrew([{...named,title:'',program:null}],[],spaces)[0].title,'t1');
assert.equal(collectCrew([{...named,title:''}],[],spaces)[0].status_ms,null);
assert.equal(collectCrew([], [{address:'kid',parent:'t1',state:'live',status:'working',name:'Incidental name',program:{name:'Child program'}}],spaces)[0].title,'Child program');
console.log('PASS: native done, child/error, settled/remote identity, shell exclusion, stable roles, bounded history, confirmed exits, revival and malformed replies');
