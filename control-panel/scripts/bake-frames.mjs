import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

if (process.argv.length !== 3 || !process.argv[2]) {
  console.error("Usage: node scripts/bake-frames.mjs /path/to/cell-motion");
  process.exit(1);
}
const source = resolve(process.argv[2]);
const version = JSON.parse(await readFile(resolve(source, "package.json"), "utf8")).version;
const commit = execFileSync("git", ["-C", source, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
if (version !== "0.1.0" || commit !== "e528cb6eb7b6e70d633480cf6d03be58be3abb47") {
  throw new Error("Expected cell-motion 0.1.0 at e528cb6; review a newer kit before rebaking.");
}
const { tui } = await import(pathToFileURL(resolve(source, "dist/terminal/index.js")));
const data = {
  source: { name: "cell-motion", version, commit, license: "MIT" },
  working: { component: "Comet", ms: 400, still: tui.cometCell(2.4)(0), frames: tui.bake(tui.cometCell(2.4), { frames: 6, seconds: 2.4 }) },
  blocked: { component: "Breathe", ms: 500, still: "▓", frames: tui.bake(tui.breathe(2.5), { frames: 5, seconds: 2.5 }) },
  done: { component: "Check (resting terminal adaptation)", still: "✓", frames: ["✓"] },
  idle: { still: "·", frames: ["·"] },
  dead: { still: "×", frames: ["×"] },
  unavailable: { still: "?", frames: ["?"] }
};
for (const name of ["working", "blocked"]) {
  const item = data[name];
  if (1000 / item.ms >= 3 || item.frames.some(frame => [...frame].length !== 1 || /[\x00-\x1f]/.test(frame))) {
    throw new Error(`Unsafe frames for ${name}`);
  }
}
const json = JSON.stringify(data, null, 2) + "\n";
await writeFile(new URL("../mods/control-panel/frames.json", import.meta.url), json);
await writeFile(new URL("../mods/control-panel/frames.js", import.meta.url),
  "// Generated by scripts/bake-frames.mjs; JSON twin avoids runtime JSON-module assumptions.\nexport default " + json.trimEnd() + ";\n");
console.log(`Baked Comet and Breathe from cell-motion ${version} (${commit.slice(0, 7)}).`);
